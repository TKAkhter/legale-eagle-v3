/**
 * Settings master registry — LMS SettingsContent tiles → v3 LookupManager / routes.
 */
export interface MasterConfig {
  key: string
  title: string
  description: string
  getUrl: string
  addUrl: string
  deleteUrl: string
  nameField: string
  statusChange?: boolean
  extraFields?: { key: string; label: string; type?: string }[]
  /** When set, hub tile navigates here instead of /masters/:key */
  href?: string
  section: "masters" | "settings"
  keywords?: string
}

