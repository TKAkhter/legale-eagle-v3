export function getMasterByKey(key: string): MasterConfig | undefined {
  return [...LOOKUP_MASTERS, ...SETTINGS_TILES].find(m => m.key === key)
}

export function masterHref(m: MasterConfig): string {
  if (m.href) return m.href
  return `/admin/settings/masters/${m.key}`
}
